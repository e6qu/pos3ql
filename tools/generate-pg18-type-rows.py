#!/usr/bin/env python3
"""Write every built-in pg_catalog pg_type row of PostgreSQL 18.6.

usage: generate-pg18-type-rows.py --dsn DSN --mode write|check
       --output src/sql/catalog_type_rows.rs

Queries a PostgreSQL 18.6 server for all 32 pg_type columns of every type in
pg_catalog, in OID order, with the names of its support routines, and writes
them with the SHA-256 digests of the extraction SQL and its `psql -At` output.
`check` fails when the written file differs from what the server returns.
pg_catalog OIDs come from the source tree and initdb's fixed order;
information_schema's types are created after initdb imports the platform's
collations, so their OIDs differ between installations and are not read here.
"""
import argparse, hashlib, json, subprocess, sys

parser = argparse.ArgumentParser()
parser.add_argument("--dsn", required=True, help="libpq connection string of a PostgreSQL 18.6 server")
parser.add_argument("--mode", choices=("write", "check"), required=True)
parser.add_argument("--output", required=True)
options = parser.parse_args()


def psql(sql):
    return subprocess.run(["psql", "-X", "-At", options.dsn, "-c", sql],
                          capture_output=True, text=True, check=True).stdout


version = psql("SHOW server_version").strip()
if not version.startswith("18.6"):
    sys.exit(f"reference server is {version}, not PostgreSQL 18.6")

columns = [
    "oid::integer", "typname::text", "typnamespace::integer", "typowner::integer",
    "typlen", "typbyval", "typtype::text", "typcategory::text", "typispreferred",
    "typisdefined", "typdelim::text", "typrelid::integer", "typsubscript::oid::integer",
    "typelem::integer", "typarray::integer", "typinput::oid::integer",
    "typoutput::oid::integer", "typreceive::oid::integer", "typsend::oid::integer",
    "typmodin::oid::integer", "typmodout::oid::integer", "typanalyze::oid::integer",
    "typalign::text", "typstorage::text", "typnotnull", "typbasetype::integer",
    "typtypmod", "typndims", "typcollation::integer", "typdefaultbin::text",
    "typdefault", "typacl::text",
]
routines = ["typsubscript", "typinput", "typoutput", "typreceive", "typsend",
            "typmodin", "typmodout", "typanalyze"]
columns += [f"{column}::text" for column in routines]
sql = ("SELECT coalesce(jsonb_agg(jsonb_build_array(" + ", ".join(columns) +
       ") ORDER BY oid), '[]') FROM pg_catalog.pg_type "
       "WHERE typnamespace = 'pg_catalog'::regnamespace")
output = psql(sql)
rows = json.loads(output)
if len(rows) != 473:
    sys.exit(f"expected PostgreSQL 18.6's 473 pg_catalog types, found {len(rows)}")


def text(value):
    return "None" if value is None else "Some(" + json.dumps(value, ensure_ascii=False) + ")"


def char(value):
    return "b" + json.dumps(value).replace('"', "'")


lines = [
    "//! Every built-in `pg_type` row of PostgreSQL 18.6, in OID order.",
    "//! Generated by tools/generate-pg18-type-rows.py; do not edit.",
    "//! Extraction SQL SHA256: " + hashlib.sha256((sql + "\n").encode()).hexdigest(),
    "//! Result JSON SHA256: " + hashlib.sha256(output.encode()).hexdigest(),
    "//! https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_type.dat",
    "",
    "/// One `pg_type` row; regproc columns hold routine OIDs (0 is `-`) and",
    "/// `routine_names` their names, in column order from `typsubscript`.",
    "#[derive(Clone, Copy, Debug)]",
    "pub(crate) struct BuiltinTypeRow {",
]
fields = [
    ("oid", "i32"), ("name", "&'static str"), ("namespace", "i32"), ("owner", "i32"),
    ("len", "i16"), ("by_value", "bool"), ("kind", "u8"), ("category", "u8"),
    ("preferred", "bool"), ("defined", "bool"), ("delimiter", "u8"), ("relation", "i32"),
    ("subscript", "i32"), ("element", "i32"), ("array", "i32"), ("input", "i32"),
    ("output", "i32"), ("receive", "i32"), ("send", "i32"), ("modifier_input", "i32"),
    ("modifier_output", "i32"), ("analyze", "i32"), ("align", "u8"), ("storage", "u8"),
    ("not_null", "bool"), ("base_type", "i32"), ("type_modifier", "i32"),
    ("dimensions", "i32"), ("collation", "i32"),
    ("default_node", "Option<&'static str>"), ("default", "Option<&'static str>"),
    ("acl", "Option<&'static str>"),
    ("routine_names", "[&'static str; 8]"),
]
for name, kind in fields:
    lines.append(f"    pub(crate) {name}: {kind},")
lines += ["}", "", "#[rustfmt::skip]", "pub(crate) const BUILTIN_TYPE_ROWS: &[BuiltinTypeRow] = &["]
for row in rows:
    row = row[:len(fields) - 1] + [row[len(fields) - 1:]]
    values = []
    for (name, kind), value in zip(fields, row):
        if kind == "u8":
            values.append(f"{name}: {char(value)}")
        elif kind.startswith("Option"):
            values.append(f"{name}: {text(value)}")
        elif kind == "&'static str":
            values.append(f"{name}: {json.dumps(value)}")
        elif kind.startswith("["):
            values.append(f"{name}: [" + ", ".join(json.dumps(v) for v in value) + "]")
        elif kind == "bool":
            values.append(f"{name}: {'true' if value else 'false'}")
        else:
            values.append(f"{name}: {value}")
    lines.append("    BuiltinTypeRow { " + ", ".join(values) + " },")
lines.append("];")
text_out = "\n".join(lines) + "\n"

if options.mode == "write":
    open(options.output, "w").write(text_out)
elif open(options.output).read() != text_out:
    sys.exit(f"{options.output} differs from the reference server")
