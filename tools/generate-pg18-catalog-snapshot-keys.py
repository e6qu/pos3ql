#!/usr/bin/env python3
"""Generate catalog row keys from catalog_snapshot_diff.py reference metadata."""

import argparse
import json
from pathlib import Path
import re


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", type=Path, required=True)
    parser.add_argument("--image", required=True)
    parser.add_argument("--reference-run", required=True)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()
    metadata = json.loads(arguments.metadata.read_text())
    version = re.match(r"PostgreSQL (18\.\d+) ", metadata["version"])
    if version is None:
        raise ValueError("catalog row keys require an actual PostgreSQL 18 release")
    keys = {}
    # The reference query orders each relation's primary key first, then its
    # other unique indexes. Any chosen columns identify at most one tuple.
    for relation, index, columns in metadata["catalog_keys"]:
        if not isinstance(columns, list) or not columns or not all(
            isinstance(name, str) and re.fullmatch(r"[a-z_]+", name) for name in columns
        ):
            raise ValueError(f"invalid key columns for {relation}.{index}")
        keys.setdefault(relation, columns)
    lines = [
        f"// Generated by tools/generate-pg18-catalog-snapshot-keys.py from PostgreSQL {version[1]}.",
        f"// Reference: {arguments.reference_run}",
        f"// Image: {arguments.image}",
        "use core::num::NonZeroU32;",
        "use super::catalog_snapshot::{CatalogRowKey, CatalogSnapshotRelation};",
        "",
        "pub(super) const RELATIONS: &[CatalogSnapshotRelation] = &[",
    ]
    names = set()
    identities = set()
    for name, oid, shared in metadata["catalog_relations"]:
        if not re.fullmatch(r"pg_[a-z_]+", name) or type(oid) is not int or not 0 < oid <= 0xFFFF_FFFF:
            raise ValueError(f"invalid catalog identity {name}: {oid}")
        if name in names or oid in identities or not isinstance(shared, bool):
            raise ValueError(f"duplicate or invalid catalog identity {name}")
        names.add(name)
        identities.add(oid)
        columns = keys.get(name)
        # An unindexed dependency catalog uses its entire tuple as the key;
        # its count preserves repeated identical dependency rows.
        row_key = "CatalogRowKey::Tuple" if columns is None else (
            "CatalogRowKey::Columns(&[" + ", ".join(json.dumps(column) for column in columns) + "])"
        )
        lines.append(
            "    CatalogSnapshotRelation { "
            f"name: {json.dumps(name)}, oid: NonZeroU32::new({oid}).unwrap(), shared: {str(shared).lower()}, key: {row_key}"
            " },"
        )
    lines.append("];")
    if not keys.keys() <= names:
        raise ValueError("catalog unique indexes refer to absent catalog relations")
    arguments.output.write_text("\n".join(lines) + "\n")
    print(f"Generated {len(names)} catalog row identities from PostgreSQL {version[1]}")


if __name__ == "__main__":
    main()
