#!/usr/bin/env python3
"""Generate src/sql/catalog_aggregate_costs.rs from a PostgreSQL 18.6 server.

usage: generate-pg18-aggregate-costs.py --dsn DSN OUTPUT

Records, per built-in aggregate, what `get_agg_clause_costs` charges: the
`procost` of its transition and final functions, the transition function and
initial value that decide whether two aggregates share one transition state
(`find_compatible_trans`), and the bytes its state adds to a hash
aggregate's entry (`transitionSpace`). A polymorphic state type is resolved
from the call's input type, so it is recorded as such.
"""
import argparse
import hashlib
import subprocess
import sys

SQL = """SELECT a.aggfnoid::oid, a.aggtransfn::oid, tf.procost, coalesce(ff.procost, 0), \
coalesce(a.agginitval, '<null>'), t.typbyval, t.typtype, t.typlen, \
a.aggtranstype = 'internal'::regtype, a.aggtransspace, \
a.aggtransfn = 'array_append'::regproc \
FROM pg_aggregate a JOIN pg_proc tf ON tf.oid = a.aggtransfn \
LEFT JOIN pg_proc ff ON ff.oid = a.aggfinalfn \
JOIN pg_type t ON t.oid = a.aggtranstype ORDER BY 1"""

ALLOCSET_SMALL_INITSIZE = 1024
ALLOCSET_DEFAULT_INITSIZE = 8 * 1024
POINTER = 8


def maxalign(value):
    return (value + 7) // 8 * 8


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dsn", required=True)
    parser.add_argument("output")
    options = parser.parse_args()
    version = subprocess.run(["psql", "-X", "-At", options.dsn, "-c", "SHOW server_version"],
                             capture_output=True, text=True, check=True).stdout.strip()
    if not version.startswith("18.6"):
        sys.exit(f"reference server is {version}, not PostgreSQL 18.6")
    out = subprocess.run(["psql", "-X", "-At", "-F", "\t", options.dsn, "-c", SQL],
                         capture_output=True, text=True, check=True).stdout
    lines = [
        "//! What PostgreSQL's planner charges for each built-in aggregate",
        "//! (`get_agg_clause_costs`), queried from PostgreSQL 18.6 (Homebrew).",
        "//! Generated by tools/generate-pg18-aggregate-costs.py.",
        f"//! Extraction SQL SHA256: {hashlib.sha256((SQL + chr(10)).encode()).hexdigest()}",
        f"//! Result SHA256: {hashlib.sha256(out.encode()).hexdigest()}",
        "//! https://github.com/postgres/postgres/blob/REL_18_6/src/backend/optimizer/prep/prepagg.c",
        "",
        "use super::{AggregateCost, TransitionSpace};",
        "",
        "#[rustfmt::skip]",
        "pub(super) const AGGREGATE_COSTS: &[(i32, AggregateCost)] = &[",
    ]
    for row in out.splitlines():
        (oid, transfn, trans_cost, final_cost, initval, byval, typtype, typlen, internal,
         transspace, array_append) = row.split("\t")
        transspace = int(transspace)
        if typtype == "p" and internal != "t":
            space = "TransitionSpace::Input"
        elif byval != "t":
            if transspace > 0:
                width = transspace
            elif array_append == "t":
                width = ALLOCSET_SMALL_INITSIZE
            else:
                width = int(typlen) if int(typlen) > 0 else 32
            space = f"TransitionSpace::Fixed({maxalign(width) + 2 * POINTER})"
        elif internal == "t":
            space = f"TransitionSpace::Fixed({transspace if transspace > 0 else ALLOCSET_DEFAULT_INITSIZE})"
        else:
            space = "TransitionSpace::Fixed(0)"
        initial = "None" if initval == "<null>" else '"' + initval.replace("\\", "\\\\").replace('"', '\\"') + '"'
        if initial != "None":
            initial = f"Some({initial})"
        lines.append(
            f"    ({oid}, AggregateCost {{ transition: {transfn}, transition_cost: {float(trans_cost)!r}, "
            f"final_cost: {float(final_cost)!r}, initial: {initial}, space: {space} }}),"
        )
    lines.append("];")
    with open(options.output, "w") as output:
        output.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
