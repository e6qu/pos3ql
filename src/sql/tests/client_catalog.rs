#[test]
fn client_catalog_vectors_keep_elements_types_and_zero_based_subscripts() {
    let config = test_config("client-catalog-vectors");
    let mut budget = test_engine_budget(&config, 1 << 29);
    let mut engine = Engine::new(&config, &mut budget).unwrap();
    let mut session = ConfiguredTransactionSession::new(&config, &mut budget);
    let selected = session.success(
        &mut engine,
        "SELECT unnest('1 2 3'::int2vector),generate_subscripts('1 2 3'::int2vector,1)",
        true,
    );
    assert_eq!(data_rows(&selected), ["1|0", "2|1", "3|2"]);
    assert_eq!(row_description_type_oids(&selected), [21, 23]);
    let expanded = session.success(
        &mut engine,
        "SELECT * FROM unnest('1 2'::int2vector,'42'::oidvector) WITH ORDINALITY",
        true,
    );
    assert_eq!(data_rows(&expanded), ["1|42|1", "2|NULL|2"]);
    assert_eq!(row_description_type_oids(&expanded), [21, 26, 20]);
    assert_eq!(
        data_rows(&session.success(
            &mut engine,
            "SELECT * FROM generate_subscripts('42 99'::oidvector,1,true)",
            true
        )),
        ["1", "0"]
    );
    for sql in [
        "SELECT unnest(''::int2vector)",
        "SELECT * FROM unnest(NULL::oidvector)",
        "SELECT generate_subscripts(''::int2vector,1)",
        "SELECT * FROM generate_subscripts('1 2'::int2vector,2)",
    ] {
        assert!(
            data_rows(&session.success(&mut engine, sql, true)).is_empty(),
            "{sql}"
        );
    }
    assert_eq!(
        data_rows(&session.success(
            &mut engine,
            "SELECT 'foo' LIKE ANY(ARRAY['f%','b%']), 'foo' LIKE ALL(ARRAY['f%','%o']), \
        'FOO' ILIKE ANY(ARRAY['f%']), 'foo' NOT LIKE ANY(ARRAY['f%','b%']), \
        'foo' NOT LIKE ALL(ARRAY['x%','y%']), 'foo' LIKE ANY('{f%,b%}'), \
        'r'::\"char\"=ANY(ARRAY['r','p'])",
            true
        )),
        ["t|t|t|t|t|t|t"]
    );
}

#[test]
fn client_catalog_regclass_names_resolve_outside_search_path() {
    let config = test_config("client-catalog-relation-names");
    let mut budget = test_engine_budget(&config, 1 << 29);
    let mut engine = Engine::new(&config, &mut budget).unwrap();
    let mut session = ConfiguredTransactionSession::new(&config, &mut budget);
    session.success(&mut engine,
        "CREATE SCHEMA client_hidden; \
        CREATE TABLE client_hidden.orders(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY); \
        CREATE INDEX orders_extra ON client_hidden.orders(id); \
        CREATE VIEW client_hidden.report AS SELECT id FROM client_hidden.orders; \
        CREATE TYPE client_hidden.order_value AS (id integer); \
        CREATE TABLE client_hidden.\"Mixed Name\"(id integer)", true);
    assert_eq!(
        data_rows(&session.success(
            &mut engine,
            "SELECT 'client_hidden.orders'::regclass::text, \
        'client_hidden.orders_id_seq'::regclass::text, \
        'client_hidden.orders_pkey'::regclass::text, \
        'client_hidden.orders_extra'::regclass::text, \
        'client_hidden.report'::regclass::text, \
        'client_hidden.order_value'::regclass::text, \
        'client_hidden.\"Mixed Name\"'::regclass::text",
            true
        )),
        [
            "client_hidden.orders|client_hidden.orders_id_seq|client_hidden.orders_pkey|client_hidden.orders_extra|client_hidden.report|client_hidden.order_value|client_hidden.\"Mixed Name\""
        ]
    );
    assert_eq!(data_rows(&session.success(&mut engine,
        "SELECT pg_get_serial_sequence(a.attrelid::regclass::text,a.attname) \
        FROM pg_attribute AS a WHERE a.attrelid='client_hidden.orders'::regclass AND a.attname='id'", true)),
        ["client_hidden.orders_id_seq"]);
    session.success(&mut engine, "SET search_path=client_hidden,public", true);
    assert_eq!(
        data_rows(&session.success(
            &mut engine,
            "SELECT 'client_hidden.orders'::regclass::text, \
        'client_hidden.orders_extra'::regclass::text, \
        'client_hidden.\"Mixed Name\"'::regclass::text",
            true
        )),
        ["orders|orders_extra|\"Mixed Name\""]
    );
    session.success(
        &mut engine,
        "CREATE TABLE public.orders(id integer); SET search_path=public,client_hidden",
        true,
    );
    assert_eq!(
        data_rows(&session.success(
            &mut engine,
            "SELECT 'client_hidden.orders'::regclass::text,'public.orders'::regclass::text",
            true
        )),
        ["client_hidden.orders|orders"]
    );
}
