#!/usr/bin/env python3
"""Generate pg_operator's built-in rows from a PostgreSQL 18 reference server.

Usage: generate-pg18-operator-rows.py --psql PATH --dsn DSN --source TEXT
       --output src/sql/catalog_operator_rows.rs [--mode write|check]

The reference must be a fresh `initdb -E UTF8 --locale=C` cluster; every row
of its pg_operator belongs to pg_catalog and the bootstrap superuser.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

QUERY = """\
SELECT o.oid, o.oprname, o.oprnamespace, o.oprowner, o.oprkind,
       o.oprcanmerge, o.oprcanhash, o.oprleft, o.oprright, o.oprresult,
       o.oprcom, o.oprnegate, o.oprcode::oid, o.oprcode::text,
       o.oprrest::oid, o.oprrest::text, o.oprjoin::oid, o.oprjoin::text
FROM pg_catalog.pg_operator o ORDER BY o.oid"""


def psql(arguments, sql):
    return subprocess.run(
        [arguments.psql, "-X", "-A", "-t", "-F", "\t", "-d", arguments.dsn, "-c", sql],
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--psql", required=True)
    parser.add_argument("--dsn", required=True)
    parser.add_argument("--source", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--mode", choices=["write", "check"], default="write")
    arguments = parser.parse_args()
    version = psql(arguments, "SELECT version()").strip()
    release = re.match(r"PostgreSQL (18\.\d+) ", version)
    if release is None:
        raise ValueError(f"operator rows require a PostgreSQL 18 release, got {version!r}")
    rows = []
    for line in psql(arguments, QUERY).splitlines():
        fields = line.split("\t")
        if len(fields) != 18:
            raise ValueError(f"unexpected operator row {line!r}")
        (oid, name, namespace, owner, kind, merges, hashes, left, right, result,
         commutator, negator, code, code_name, rest, rest_name, join, join_name) = fields
        if (namespace, owner) != ("11", "10") or kind not in "blr" or len(kind) != 1:
            raise ValueError(f"operator {oid} is not a built-in pg_catalog row")
        for flag in (merges, hashes):
            if flag not in ("t", "f"):
                raise ValueError(f"operator {oid} has an invalid flag")
        rows.append(
            "    ("
            + ", ".join(
                [
                    oid,
                    json.dumps(name),
                    f"b'{kind}'",
                    str(merges == "t").lower(),
                    str(hashes == "t").lower(),
                    left,
                    right,
                    result,
                    commutator,
                    negator,
                    code,
                    json.dumps(code_name),
                    rest,
                    json.dumps(rest_name),
                    join,
                    json.dumps(join_name),
                ]
            )
            + "),"
        )
    query_hash = hashlib.sha256(QUERY.encode()).hexdigest()
    text = "\n".join(
        [
            f"//! Every built-in `pg_operator` row of PostgreSQL {release[1]}, in OID order:",
            "//! OID, name, kind, merges, hashes, left, right and result type OIDs,",
            "//! commutator, negator, then the implementation, restriction and join",
            "//! estimator routines as (OID, name), with OID 0 and `-` for none.",
            "//! Generated by tools/generate-pg18-operator-rows.py; do not edit.",
            f"//! Reference: {version}",
            f"//! Source: {arguments.source}",
            f"//! Extraction SQL SHA256: {query_hash}",
            "",
            "pub(super) type OperatorRow = (",
            "    i32,",
            "    &'static str,",
            "    u8,",
            "    bool,",
            "    bool,",
            "    i32,",
            "    i32,",
            "    i32,",
            "    i32,",
            "    i32,",
            "    i32,",
            "    &'static str,",
            "    i32,",
            "    &'static str,",
            "    i32,",
            "    &'static str,",
            ");",
            "",
            "#[rustfmt::skip]",
            f"pub(super) static OPERATOR_ROWS: [OperatorRow; {len(rows)}] = [",
            *rows,
            "];",
            "",
        ]
    )
    if arguments.mode == "check":
        if arguments.output.read_text() != text:
            raise SystemExit(f"{arguments.output} differs from the reference")
        return
    arguments.output.write_text(text)


if __name__ == "__main__":
    main()
