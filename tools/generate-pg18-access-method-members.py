#!/usr/bin/env python3
"""Generate pg_amop's and pg_amproc's built-in rows, and pg_opclass's physical
row order, from a PostgreSQL 18.6 reference server.

Usage: generate-pg18-access-method-members.py --psql PATH --dsn DSN
       --output src/sql/catalog_access_method_members.rs [--mode write|check]

The reference must be a fresh `initdb -E UTF8 --locale=C` cluster. Every row
it lists has an OID below 12000: genbki assigns them while loading pg_amop.dat and
pg_amproc.dat, so they are the same on every platform.
"""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess

OPERATORS = """\
SELECT oid, amopfamily, amoplefttype, amoprighttype, amopstrategy, amoppurpose,
       amopopr, amopmethod, amopsortfamily
FROM pg_catalog.pg_amop ORDER BY oid"""
CLASS_ORDER = "SELECT oid FROM pg_catalog.pg_opclass"
PROCEDURES = """\
SELECT oid, amprocfamily, amproclefttype, amprocrighttype, amprocnum,
       amproc::oid, amproc::text
FROM pg_catalog.pg_amproc ORDER BY oid"""


def psql(arguments, sql):
    return subprocess.run(
        [arguments.psql, "-X", "-A", "-t", "-F", "\t", "-d", arguments.dsn, "-c", sql],
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--psql", required=True)
    parser.add_argument("--dsn", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--mode", choices=["write", "check"], default="write")
    arguments = parser.parse_args()
    version = psql(arguments, "SHOW server_version").strip()
    if not version.startswith("18.6"):
        raise ValueError(f"access method members require PostgreSQL 18.6, got {version!r}")
    operator_output = psql(arguments, OPERATORS)
    procedure_output = psql(arguments, PROCEDURES)
    class_output = psql(arguments, CLASS_ORDER)
    lines = [
        "//! Every built-in `pg_amop` and `pg_amproc` row of PostgreSQL 18.6, in OID",
        "//! order. Generated by tools/generate-pg18-access-method-members.py; do not edit.",
        "//! Source: fresh initdb -E UTF8 --locale=C; rows come from",
        "//! https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_amop.dat",
        "//! and https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_amproc.dat",
        "//! Operator SQL SHA256: " + hashlib.sha256(OPERATORS.encode()).hexdigest(),
        "//! Operator rows SHA256: " + hashlib.sha256(operator_output.encode()).hexdigest(),
        "//! Procedure SQL SHA256: " + hashlib.sha256(PROCEDURES.encode()).hexdigest(),
        "//! Procedure rows SHA256: " + hashlib.sha256(procedure_output.encode()).hexdigest(),
        "//! Class order SQL SHA256: " + hashlib.sha256(CLASS_ORDER.encode()).hexdigest(),
        "//! Class order SHA256: " + hashlib.sha256(class_output.encode()).hexdigest(),
        "",
        "/// `(oid, family, left type, right type, strategy, purpose, operator, method,",
        "/// sort family)`.",
        "pub(super) type OperatorRow = (i32, i32, i32, i32, i16, &'static str, i32, i32, i32);",
        "",
        "#[rustfmt::skip]",
        "pub(super) const OPERATORS: &[OperatorRow] = &[",
    ]
    for line in operator_output.splitlines():
        fields = line.split("\t")
        if len(fields) != 9 or int(fields[0]) >= 12000 or fields[5] not in ("s", "o"):
            raise ValueError(f"unexpected pg_amop row {line!r}")
        oid, family, left, right, strategy, purpose, operator, method, sort = fields
        lines.append(
            f"    ({oid}, {family}, {left}, {right}, {strategy}, \"{purpose}\", "
            f"{operator}, {method}, {sort}),"
        )
    lines += [
        "];",
        "",
        "/// `(oid, family, left type, right type, support number, routine OID, routine)`.",
        "#[rustfmt::skip]",
        "pub(super) const PROCEDURES: &[(i32, i32, i32, i32, i16, i32, &str)] = &[",
    ]
    for line in procedure_output.splitlines():
        fields = line.split("\t")
        if len(fields) != 7 or int(fields[0]) >= 12000 or not re.fullmatch(r"[a-z0-9_.]+", fields[6]):
            raise ValueError(f"unexpected pg_amproc row {line!r}")
        oid, family, left, right, number, routine, name = fields
        lines.append(
            f"    ({oid}, {family}, {left}, {right}, {number}, {routine}, \"{name}\"),"
        )
    lines += [
        "];",
        "",
        "/// Built-in `pg_opclass` OIDs in the physical order a fresh cluster scans them,",
        "/// which unordered aggregates over the catalog observe.",
        "#[rustfmt::skip]",
        "pub(super) const OPERATOR_CLASS_ORDER: &[i32] = &[",
    ]
    for line in class_output.splitlines():
        if not line.isdigit() or int(line) >= 12000:
            raise ValueError(f"unexpected pg_opclass OID {line!r}")
        lines.append(f"    {line},")
    lines.append("];")
    text = "\n".join(lines) + "\n"
    if arguments.mode == "write":
        arguments.output.write_text(text)
    elif arguments.output.read_text() != text:
        raise SystemExit(f"{arguments.output} differs from the reference server")


if __name__ == "__main__":
    main()
