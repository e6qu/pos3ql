class TranslateError(Exception):
    pass


# ---------------------------------------------------------------- lexing ---

TOKEN = re.compile(
    r"""\s+|/\*.*?\*/|//[^\n]*|
    (?P<char>'(?:\\.|[^\\'])')|
    (?P<num>0[xX][0-9a-fA-F]+|\d+)|
    (?P<id>[A-Za-z_][A-Za-z0-9_]*)|
    (?P<op>->|\+\+|--|<=|>=|==|!=|&&|\|\||<<|>>|\+=|-=|[-+*/%<>=!&|^~(){}\[\];,:?.])""",
    re.S | re.X,
)
CHAR_ESCAPES = {"\\'": 39, "\\\\": 92, "\\n": 10, "\\t": 9, "\\0": 0}


def tokenize(source):
    tokens = []
    at = 0
    while at < len(source):
        match = TOKEN.match(source, at)
        if match is None:
            raise TranslateError(f"cannot tokenize near {source[at:at + 40]!r}")
        at = match.end()
        if match.group("char"):
            body = match.group("char")[1:-1]
            tokens.append(("num", str(CHAR_ESCAPES[body] if body.startswith("\\") else ord(body))))
        elif match.group("num"):
            tokens.append(("num", str(int(match.group("num"), 0))))
        elif match.group("id"):
            tokens.append(("id", match.group("id")))
        elif match.group("op"):
            tokens.append(("op", match.group("op")))
    tokens.append(("eof", ""))
    return tokens


# ----------------------------------------------------------- C parsing ---

class Parser:
    def __init__(self, tokens):
        self.tokens = tokens
        self.at = 0

    def peek(self, offset=0):
        return self.tokens[self.at + offset]

    def take(self, kind=None, value=None):
        token = self.tokens[self.at]
        if (kind and token[0] != kind) or (value is not None and token[1] != value):
            raise TranslateError(f"expected {value or kind}, found {token}")
        self.at += 1
        return token

    def accept(self, value):
        if self.peek()[1] == value and self.peek()[0] in ("op", "id"):
            self.at += 1
            return True
        return False

    # Statements are tuples whose first element names the kind.
    def compound(self):
        self.take("op", "{")
        items = []
        while not self.accept("}"):
            items.extend(self.statement_items())
        return ("block", items)

    def statement_items(self):
        token = self.peek()
        if token[0] == "id" and self.peek(1) == ("op", ":") and token[1] not in ("default",):
            self.at += 2
            return [("label", token[1])]
        if token == ("id", "case"):
            self.at += 1
            value = int(self.take("num")[1])
            self.take("op", ":")
            return [("case", value)]
        if token == ("id", "int"):
            self.at += 1
            declarations = []
            while True:
                name = self.take("id")[1]
                init = self.expression() if self.accept("=") else None
                declarations.append(("decl", name, init))
                if self.accept(";"):
                    return declarations
                self.take("op", ",")
        return [self.statement()]

    def statement(self):
        token = self.peek()
        if token == ("op", "{"):
            return self.compound()
        if token == ("op", ";"):
            self.at += 1
            return ("block", [])
        if token[0] == "id":
            word = token[1]
            if word == "if":
                self.at += 1
                self.take("op", "(")
                condition = self.expression()
                self.take("op", ")")
                then = self.statement()
                otherwise = self.statement() if self.accept("else") else None
                return ("if", condition, then, otherwise)
            if word == "while":
                self.at += 1
                self.take("op", "(")
                condition = self.expression()
                self.take("op", ")")
                if condition != ("num", 1):
                    raise TranslateError("only while(1) loops are generated by Snowball")
                return ("loop", self.statement())
            if word == "for":
                self.at += 1
                self.take("op", "(")
                init = self.expression()
                self.take("op", ";")
                condition = self.expression()
                self.take("op", ";")
                step = self.expression()
                self.take("op", ")")
                return ("for", init, condition, step, self.statement())
            if word == "switch":
                self.at += 1
                self.take("op", "(")
                subject = self.expression()
                self.take("op", ")")
                return ("switch", subject, self.compound()[1])
            if word == "goto":
                self.at += 1
                label = self.take("id")[1]
                self.take("op", ";")
                return ("goto", label)
            if word in ("break", "continue"):
                self.at += 1
                self.take("op", ";")
                return (word,)
            if word == "return":
                self.at += 1
                value = None if self.peek() == ("op", ";") else self.expression()
                self.take("op", ";")
                return ("return", value)
        expression = self.expression()
        self.take("op", ";")
        return ("expr", expression)

    # Expressions: ("num", n), ("var", name), ("field", name), ("index", base, e),
    # ("call", name, args), ("unary", op, e), ("binary", op, l, r),
    # ("assign", op, target, value), ("post", op, target), ("void", e).
    BINARY = [
        ["||"], ["&&"], ["|"], ["^"], ["&"], ["==", "!="],
        ["<", "<=", ">", ">="], ["<<", ">>"], ["+", "-"], ["*", "/", "%"],
    ]

    def expression(self):
        left = self.binary(0)
        token = self.peek()
        if token[0] == "op" and token[1] in ("=", "+=", "-="):
            self.at += 1
            return ("assign", token[1], left, self.expression())
        return left

    def binary(self, level):
        if level == len(self.BINARY):
            return self.unary()
        left = self.binary(level + 1)
        while self.peek()[0] == "op" and self.peek()[1] in self.BINARY[level]:
            op = self.take()[1]
            left = ("binary", op, left, self.binary(level + 1))
        return left

    def unary(self):
        token = self.peek()
        if token[0] == "op" and token[1] in ("!", "-", "~"):
            self.at += 1
            return ("unary", token[1], self.unary())
        if token == ("op", "(") and self.peek(1) == ("id", "void"):
            self.at += 2
            self.take("op", ")")
            return ("void", self.unary())
        return self.postfix()

    def postfix(self):
        token = self.take()
        if token[0] == "num":
            node = ("num", int(token[1]))
        elif token[0] == "id":
            node = ("var", token[1])
            if self.peek() == ("op", "("):
                self.at += 1
                arguments = []
                if not self.accept(")"):
                    while True:
                        arguments.append(self.expression())
                        if self.accept(")"):
                            break
                        self.take("op", ",")
                node = ("call", token[1], arguments)
        elif token == ("op", "("):
            node = self.expression()
            self.take("op", ")")
        else:
            raise TranslateError(f"unexpected token {token}")
        while True:
            token = self.peek()
            if token == ("op", "->"):
                self.at += 1
                if node != ("var", "z"):
                    raise TranslateError("only the environment is dereferenced")
                node = ("field", self.take("id")[1])
            elif token == ("op", "["):
                self.at += 1
                index = self.expression()
                self.take("op", "]")
                node = ("index", node, index)
            elif token[0] == "op" and token[1] in ("++", "--"):
                self.at += 1
                node = ("post", token[1], node)
            else:
                return node


# -------------------------------------------------------------- emitting ---

RUST_PRECEDENCE = {
    "||": 1, "&&": 2, "==": 3, "!=": 3, "<": 3, "<=": 3, ">": 3, ">=": 3,
    "|": 4, "^": 5, "&": 6, "<<": 7, ">>": 7, "+": 8, "-": 8, "*": 9, "/": 9, "%": 9,
}
COMPARISONS = {"==", "!=", "<", "<=", ">", ">="}
FIELDS = {"c", "l", "lb", "bra", "ket"}


def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


class Function:
    def __init__(self, translator, name, body):
        self.translator = translator
        self.name = name
        self.body = body
        self.labels = 0
        self.loop_stack = []
        self.assigned = {}
        self.used = {}
        self.scan(body)

    def scan(self, node):
        if isinstance(node, tuple):
            if node[0] == "assign" and node[2][0] == "var":
                self.assigned[node[2][1]] = self.assigned.get(node[2][1], 0) + 1
            if node[0] == "post" and node[2][0] == "var":
                self.assigned[node[2][1]] = self.assigned.get(node[2][1], 0) + 1
            if node[0] == "var":
                self.used[node[1]] = self.used.get(node[1], 0) + 1
            if node[0] == "void":
                return
            for child in node[1:]:
                self.scan(child)
        elif isinstance(node, list):
            for child in node:
                self.scan(child)

    # Expressions return (text, kind, precedence); kind is "int" or "bool".
    def expr(self, node):
        kind = node[0]
        if kind == "num":
            return (str(node[1]), "int", 100)
        if kind == "var":
            name = node[1]
            if name in self.translator.symbols:
                return (self.translator.symbols[name], "bytes", 100)
            return (name, "int", 100)
        if kind == "field":
            if node[1] not in FIELDS:
                raise TranslateError(f"unknown field {node[1]}")
            return (f"z.{node[1]}", "int", 100)
        if kind == "index":
            base, index = node[1], node[2]
            if base == ("field", "I"):
                if index[0] != "num" or index[1] >= MAX_INTEGERS:
                    raise TranslateError("integer variable index exceeds the runtime")
                return (f"z.i[{index[1]}]", "int", 100)
            if base == ("field", "p"):
                return (f"z.byte({self.int(index)})", "int", 100)
            raise TranslateError(f"unsupported index {node}")
        if kind == "call":
            return (self.call(node[1], node[2]), "int", 100)
        if kind == "unary":
            op = node[1]
            if op == "!":
                inner = node[2]
                text, inner_kind, precedence = self.expr(inner)
                if inner_kind == "bool":
                    return ("!" + self.paren(text, precedence, 10), "bool", 10)
                return (f"{self.paren(text, precedence, 4)} == 0", "bool", 3)
            text = self.int(node[2])
            return (op.replace("~", "!") + self.paren(text, self.expr(node[2])[2], 10), "int", 10)
        if kind == "binary":
            op, left, right = node[1], node[2], node[3]
            precedence = RUST_PRECEDENCE[op]
            if op in ("&&", "||"):
                left_text, left_prec = self.boolean(left)
                right_text, right_prec = self.boolean(right)
                kind_out = "bool"
            else:
                left_text, _, left_prec = self.expr(left)
                right_text, _, right_prec = self.expr(right)
                left_text = self.as_int(left)
                right_text = self.as_int(right)
                kind_out = "bool" if op in COMPARISONS else "int"
            # Parenthesize shifts and arithmetic inside bit operations, and
            # arithmetic inside shifts, so the grouping reads as in C.
            if op in ("&", "|", "^", "<<", ">>"):
                left_text = self.group(left_text, left, op)
                right_text = self.group(right_text, right, op)
            left_text = self.paren(left_text, left_prec, precedence, left)
            right_text = self.paren(right_text, right_prec, precedence + 1, right)
            return (f"{left_text} {op} {right_text}", kind_out, precedence)
        raise TranslateError(f"unsupported expression {node}")

    def group(self, text, node, op):
        if node[0] != "binary":
            return text
        inner = node[1]
        loose = {"+", "-", "*", "/", "%"} | ({"<<", ">>"} if op in ("&", "|", "^") else set())
        if inner in loose and not text.startswith("("):
            return f"({text})"
        return text

    def paren(self, text, precedence, needed, node=None):
        return text if precedence >= needed else f"({text})"

    def as_int(self, node):
        text, kind, precedence = self.expr(node)
        if kind == "bool":
            return f"i32::from({text})"
        return text

    def int(self, node):
        return self.as_int(node)

    def boolean(self, node):
        text, kind, precedence = self.expr(node)
        if kind == "bool":
            return text, precedence
        return f"{self.paren(text, precedence, 4)} != 0", 3

    def call(self, name, args):
        symbols = self.translator.symbols
        rendered = []

        def arg(index):
            return self.int(args[index])

        def symbol(index):
            node = args[index]
            if node == ("num", 0):
                return "b\"\""
            if node[0] != "var" or node[1] not in symbols:
                raise TranslateError(f"{name} expects a symbol table, found {node}")
            return symbols[node[1]]

        def grouping(index):
            node = args[index]
            if node[0] != "var" or node[1] not in self.translator.groupings:
                raise TranslateError(f"{name} expects a grouping, found {node}")
            return self.translator.groupings[node[1]]

        def environment(index=0):
            if args[index] != ("var", "z"):
                raise TranslateError(f"{name} must receive the environment first")

        if name in ("in_grouping_U", "in_grouping_b_U", "out_grouping_U", "out_grouping_b_U"):
            environment()
            method = snake(name).replace("_u", "_utf8")
            repeat = args[4]
            if repeat not in (("num", 0), ("num", 1)):
                raise TranslateError(f"{name} repeat flag must be a constant")
            return f"z.{method}({grouping(1)}, {arg(2)}, {arg(3)}, {'true' if repeat[1] else 'false'})"
        if name in ("eq_s", "eq_s_b"):
            environment()
            return f"z.{name}({symbol(2)})"
        if name == "slice_from_s":
            environment()
            return f"z.slice_from({symbol(2)})"
        if name == "slice_del":
            environment()
            return "z.slice_del()"
        if name == "insert_s":
            environment()
            return f"z.insert({arg(1)}, {arg(2)}, {symbol(4)})"
        if name in ("find_among", "find_among_b"):
            environment()
            table = args[1]
            if table[0] != "var" or table[1] not in self.translator.amongs:
                raise TranslateError(f"{name} expects an among table")
            return f"{name}(z, {self.translator.amongs[table[1]]})"
        if name in ("skip_utf8", "skip_b_utf8"):
            if args[0] != ("field", "p"):
                raise TranslateError(f"{name} must read the current buffer")
            return f"z.{name}({arg(1)}, {arg(2)}, {arg(3)})"
        if name == "len_utf8":
            if args != [("field", "p")]:
                raise TranslateError("len_utf8 must read the current buffer")
            return "z.len_utf8()"
        if name == "slice_to_s":
            environment()
            return f"z.slice_to_s({arg(1)})"
        if name == "eq_v_b_s":
            environment()
            return f"z.eq_v_b_s({arg(1)})"
        if name in self.translator.routines:
            environment()
            return f"{self.translator.routines[name]}(z)"
        raise TranslateError(f"unsupported call {name}")

    # Statements ---------------------------------------------------------

    def emit(self):
        out = []
        self.block_items(self.body[1], out, 1, top=True)
        return out

    def contains_goto(self, node, label):
        if isinstance(node, tuple):
            if node[0] == "goto" and node[1] == label:
                return True
            return any(self.contains_goto(child, label) for child in node[1:])
        if isinstance(node, list):
            return any(self.contains_goto(child, label) for child in node)
        return False

    def regions(self, items):
        regions = []
        for index, item in enumerate(items):
            if item[0] != "label":
                continue
            start = next((j for j in range(index) if self.contains_goto(items[j], item[1])), None)
            later = any(self.contains_goto(items[j], item[1]) for j in range(index + 1, len(items)))
            if later:
                raise TranslateError(f"backward goto to {item[1]}")
            if start is not None:
                regions.append([start, index, item[1]])
        changed = True
        while changed:
            changed = False
            for outer in regions:
                for inner in regions:
                    if outer[0] < inner[0] < outer[1] < inner[1]:
                        inner[0] = outer[0]
                        changed = True
        return regions

    def block_items(self, items, out, depth, top=False, trailing_break=None):
        regions = self.regions(items)
        declared = set()
        for item in items:
            if item[0] == "decl":
                declared.add(item[1])
        # A declaration inside a labeled block must not be read after it.
        for start, end, label in regions:
            inner = {item[1] for item in items[start:end] if item[0] == "decl"}
            for name in inner:
                if any(self.mentions(item, name) for item in items[end:]):
                    raise TranslateError(f"{name} escapes labeled block {label}")
        opens = {}
        for start, end, label in regions:
            opens.setdefault(start, []).append((end, label))
        indent = "    " * depth
        stack = []
        reachable = True
        for index, item in enumerate(items):
            while stack and stack[-1][0] == index:
                end, label = stack.pop()
                depth -= 1
                indent = "    " * depth
                out.append(f"{indent}}}")
                reachable = True
            for end, label in sorted(opens.get(index, []), key=lambda region: -region[0]):
                out.append(f"{indent}'{label}: {{")
                stack.append((end, label))
                depth += 1
                indent = "    " * depth
                reachable = True
            if item[0] == "label":
                reachable = True
                continue
            if item[0] == "case":
                raise TranslateError("case label outside switch")
            if not reachable:
                continue
            is_last = index == len(items) - 1 and not stack
            if item == ("break",) and trailing_break is not None and is_last:
                continue
            self.stmt(item, out, depth, last=is_last and top, scope=items[index + 1 :])
            if self.terminates(item):
                reachable = False
        while stack:
            stack.pop()
            depth -= 1
            out.append(f"{'    ' * depth}}}")

    def mentions(self, node, name):
        if isinstance(node, tuple):
            if node[0] == "var" and node[1] == name:
                return True
            return any(self.mentions(child, name) for child in node[1:])
        if isinstance(node, list):
            return any(self.mentions(child, name) for child in node)
        return False

    def terminates(self, item):
        if item[0] in ("goto", "return", "break", "continue"):
            return True
        if item[0] == "block":
            return any(self.terminates(child) for child in item[1] if child[0] != "label") and not any(
                child[0] == "label" for child in item[1]
            )
        return False

    def scope_usage(self, items, name):
        """Reads, assignments and whether one is in a loop, after a declaration."""
        counts = [0, 0, False]

        def visit(node, looping):
            if isinstance(node, list):
                for child in node:
                    visit(child, looping)
                return
            if not isinstance(node, tuple):
                return
            if node and node[0] == "decl" and node[1] == name:
                raise TranslateError(f"{name} is redeclared in its own scope")
            if node[0] == "for":
                visit(node[4], True)
                return
            if node[0] in ("assign", "post") and node[2] == ("var", name):
                counts[1] += 1
                counts[2] = counts[2] or looping
                if node[0] == "assign":
                    visit(node[3], looping)
                return
            if node[0] == "var" and node[1] == name:
                counts[0] += 1
            if node[0] == "void":
                return
            for child in node[1:]:
                visit(child, looping or node[0] == "loop")

        visit(items, False)
        return counts

    def stmt(self, item, out, depth, last=False, scope=None):
        indent = "    " * depth
        kind = item[0]
        if kind == "decl":
            name, init = item[1], item[2]
            used, assigned, in_loop = self.scope_usage(scope or [], name)
            if used == 0 and assigned == 0:
                return
            if init is None:
                mutable = assigned > 1 or in_loop
                out.append(f"{indent}let {'mut ' if mutable else ''}{name}: i32;")
                return
            text = self.int(init)
            out.append(f"{indent}let {'mut ' if assigned else ''}{name} = {text};")
            return
        if kind == "expr":
            node = item[1]
            if node[0] == "void":
                return
            out.append(f"{indent}{self.expr_stmt(node)};")
            return
        if kind == "block":
            if not item[1]:
                return
            out.append(f"{indent}{{")
            self.block_items(item[1], out, depth + 1)
            out.append(f"{indent}}}")
            return
        if kind == "if":
            self.if_stmt(item, out, depth, indent)
            return
        if kind == "goto":
            out.append(f"{indent}break '{item[1]};")
            return
        if kind == "return":
            value = "" if item[1] is None else " " + self.int(item[1])
            if last:
                out.append(f"{indent}{value.strip()}")
            else:
                out.append(f"{indent}return{value};")
            return
        if kind in ("break", "continue"):
            if not self.loop_stack:
                raise TranslateError(f"{kind} outside a loop or switch")
            target, target_kind = self.loop_stack[-1]
            if target_kind == "switch" and kind == "continue":
                target = next(label for label, k in reversed(self.loop_stack) if k == "loop")
            out.append(f"{indent}{kind} '{target};")
            return
        if kind == "loop":
            self.labels += 1
            label = f"loop{self.labels}"
            self.loop_stack.append((label, "loop"))
            body = item[1][1] if item[1][0] == "block" else [item[1]]
            lines = []
            self.block_items(body, lines, depth + 1)
            out.append(f"{indent}{self.used_label(label, lines)}loop {{")
            out.extend(lines)
            out.append(f"{indent}}}")
            self.loop_stack.pop()
            return
        if kind == "for":
            init, condition, step, body = item[1], item[2], item[3], item[4]
            if not (
                init[0] == "assign" and init[2][0] == "var" and init[3][0] == "num"
                and condition == ("binary", ">", init[2], ("num", 0))
                and step == ("post", "--", init[2])
                and not self.mentions(body, init[2][1])
            ):
                raise TranslateError("only counted repetition loops are generated by Snowball")
            self.labels += 1
            label = f"loop{self.labels}"
            self.loop_stack.append((label, "loop"))
            body_items = body[1] if body[0] == "block" else [body]
            lines = []
            self.block_items(body_items, lines, depth + 1)
            out.append(f"{indent}{self.used_label(label, lines)}for _ in 0..{init[3][1]} {{")
            out.extend(lines)
            out.append(f"{indent}}}")
            self.loop_stack.pop()
            return
        if kind == "switch":
            self.switch(item, out, depth, indent)
            return
        raise TranslateError(f"unsupported statement {item}")

    @staticmethod
    def used_label(label, lines):
        if any(f"'{label};" in line for line in lines):
            return f"'{label}: "
        return ""

    def if_stmt(self, item, out, depth, indent, prefix="if"):
        condition, _ = self.boolean(item[1])
        out.append(f"{indent}{prefix} {condition} {{")
        then = item[2][1] if item[2][0] == "block" else [item[2]]
        self.block_items(then, out, depth + 1)
        otherwise = item[3]
        if otherwise is None:
            out.append(f"{indent}}}")
        elif otherwise[0] == "if":
            self.if_stmt(otherwise, out, depth, indent, prefix="} else if")
        else:
            out.append(f"{indent}}} else {{")
            body = otherwise[1] if otherwise[0] == "block" else [otherwise]
            self.block_items(body, out, depth + 1)
            out.append(f"{indent}}}")

    def switch(self, item, out, depth, indent):
        subject = self.int(item[1])
        cases = []
        for entry in item[2]:
            if entry[0] == "case":
                cases.append((entry[1], []))
            elif not cases:
                raise TranslateError("statement before the first case")
            else:
                cases[-1][1].append(entry)
        self.labels += 1
        label = f"switch{self.labels}"
        needs_label = any(
            self.has_inner_break(body[:-1] if body and body[-1] == ("break",) else body)
            for _, body in cases
        )
        self.loop_stack.append((label, "switch"))
        inner = depth
        if needs_label:
            out.append(f"{indent}'{label}: {{")
            inner += 1
        pad = "    " * inner
        if len(cases) == 1:
            value, body = cases[0]
            out.append(f"{pad}if {subject} == {value} {{")
            self.block_items(body, out, inner + 1, trailing_break=label)
            out.append(f"{pad}}}")
        else:
            out.append(f"{pad}match {subject} {{")
            for value, body in cases:
                out.append(f"{pad}    {value} => {{")
                self.block_items(body, out, inner + 2, trailing_break=label)
                out.append(f"{pad}    }}")
            out.append(f"{pad}    _ => {{}}")
            out.append(f"{pad}}}")
        if needs_label:
            out.append(f"{indent}}}")
        self.loop_stack.pop()

    def has_inner_break(self, node):
        if isinstance(node, tuple):
            if node[0] == "break":
                return True
            if node[0] in ("loop", "for", "switch"):
                return False
            return any(self.has_inner_break(child) for child in node[1:])
        if isinstance(node, list):
            return any(self.has_inner_break(child) for child in node)
        return False

    def expr_stmt(self, node):
        if node[0] == "assign":
            op, target, value = node[1], node[2], node[3]
            target_text = self.lvalue(target)
            return f"{target_text} {op} {self.int(value)}"
        if node[0] == "post":
            target_text = self.lvalue(node[2])
            return f"{target_text} {'+=' if node[1] == '++' else '-='} 1"
        if node[0] == "call":
            raise TranslateError(f"discarded call result {node}")
        raise TranslateError(f"unsupported expression statement {node}")

    def lvalue(self, node):
        if node[0] == "var":
            return node[1]
        if node[0] == "field" and node[1] in FIELDS:
            return f"z.{node[1]}"
        if node[0] == "index" and node[1] == ("field", "I") and node[2][0] == "num":
            return f"z.i[{node[2][1]}]"
        raise TranslateError(f"unsupported assignment target {node}")


class Translator:
    def __init__(self, language, source):
        self.language = language
        self.symbols = {}
        self.groupings = {}
        self.amongs = {}
        self.routines = {}
        self.items = []
        self.integers = 0
        self.strings = 0
        self.parse(source)

    def parse(self, source):
        # A string variable is copied with `slice_to` and compared with `eq_v_b`.
        source = re.sub(
            r"z->S\[(\d+)\] = slice_to\(z, z->S\[\1\]\);\s*if \(z->S\[\1\] == 0\) return -1;",
            r"if (!slice_to_s(z, \1)) return -1;",
            source,
        )
        source = re.sub(r"eq_v_b\(z, z->S\[(\d+)\]\)", r"eq_v_b_s(z, \1)", source)
        if "z->S" in source:
            raise TranslateError("unsupported string variable use")
        create = re.search(r"SN_create_env\((\d+), (\d+)\)", source)
        self.strings, self.integers = int(create.group(1)), int(create.group(2))
        if self.strings > MAX_STRINGS or self.integers > MAX_INTEGERS:
            raise TranslateError("environment exceeds the runtime's variables")
        for match in re.finditer(r"static const symbol (s_\w+)\[\d*\] = \{([^}]*)\};", source):
            values = [int(token[1]) for token in tokenize(match.group(2)) if token[0] == "num"]
            self.symbols[match.group(1)] = (match.group(1).upper(), bytes(values))
        for match in re.finditer(r"static const unsigned char (g_\w+)\[\] = \{([^}]*)\};", source):
            values = [int(value, 0) for value in match.group(2).split(",")]
            self.groupings[match.group(1)] = (self.unique_const(match.group(1)), values)
        for match in re.finditer(r"static int (r_\w+)\(struct SN_env \* z\) \{", source):
            self.routines[match.group(1)] = snake(match.group(1))
        stem_name = f"{self.language}_UTF_8_stem"
        self.routines[stem_name] = "stem"
        names = list(self.routines.values())
        if len(set(names)) != len(names):
            raise TranslateError("routine names collide after lowercasing")
        among_entry = re.compile(r"\{\s*(-?\d+),\s*(\w+),\s*(-?\d+),\s*(-?\d+),\s*(\w+)\s*\}")
        for match in re.finditer(r"static const struct among (a_\d+)\[(\d+)\] =\s*\{(.*?)\n\};", source, re.S):
            entries = []
            for entry in among_entry.finditer(match.group(3)):
                size, string, substring, result, function = entry.groups()
                symbol = b"" if string == "0" else self.symbols[string][1]
                if len(symbol) != int(size):
                    raise TranslateError(f"among entry length mismatch in {match.group(1)}")
                routine = None if function == "0" else self.routines[function]
                entries.append((symbol, int(substring), int(result), routine))
            if len(entries) != int(match.group(2)):
                raise TranslateError(f"among table {match.group(1)} size mismatch")
            self.amongs[match.group(1)] = (match.group(1).upper(), entries)
        # Symbol tables referenced only through among tables are inlined there.
        self.symbol_text = {name: const for name, (const, _) in self.symbols.items()}
        self.functions = []
        for match in re.finditer(
            r"^(?:static|extern) int (r_\w+|\w+_UTF_8_stem)\(struct SN_env \* z\) \{", source, re.M
        ):
            start = match.end() - 1
            depth = 0
            for end in range(start, len(source)):
                if source[end] == "{":
                    depth += 1
                elif source[end] == "}":
                    depth -= 1
                    if depth == 0:
                        break
            body = Parser(tokenize(source[start : end + 1])).compound()
            self.functions.append((match.group(1), body))

    def unique_const(self, name):
        const = name.upper()
        if any(existing[0] == const for existing in self.groupings.values()):
            raise TranslateError(f"grouping {name} collides after upper-casing")
        return const

    def render(self):
        symbols = {name: const for name, (const, _) in self.symbols.items()}
        groupings = {name: const for name, (const, _) in self.groupings.items()}
        amongs = {name: const for name, (const, _) in self.amongs.items()}
        view = type("View", (), {})()
        view.symbols = symbols
        view.groupings = groupings
        view.amongs = amongs
        view.routines = self.routines
        lines = []
        used_symbols = set()
        bodies = []
        for name, body in self.functions:
            function = Function(view, name, body)
            emitted = function.emit()
            rust_name = self.routines[name]
            visibility = "pub(super) " if rust_name == "stem" else ""
            bodies.append(f"{visibility}fn {rust_name}(z: &mut Env) -> i32 {{")
            bodies.extend(emitted)
            bodies.append("}")
            bodies.append("")
            for line in emitted:
                for symbol in re.findall(r"\bS_[0-9_]+\b", line):
                    used_symbols.add(symbol)
        for name, (const, values) in self.symbols.items():
            if const in used_symbols:
                lines.append(f"const {const}: &[u8] = {byte_string(values)};")
        if lines:
            lines.append("")
        for name, (const, values) in self.groupings.items():
            lines.append(f"const {const}: &[u8] = &{list(values)};".replace("[", "[", 1))
        if self.groupings:
            lines.append("")
        for name, (const, entries) in self.amongs.items():
            lines.append(f"const {const}: &[Among] = &[")
            for symbol, substring, result, routine in entries:
                function = "None" if routine is None else f"Some({routine})"
                lines.append(
                    f"    Among {{ s: {byte_string(symbol)}, substring_i: {substring}, "
                    f"result: {result}, function: {function} }},"
                )
            lines.append("];")
            lines.append("")
        return lines + bodies


def byte_string(values):
    text = []
    for value in values:
        if 0x20 <= value < 0x7F and value not in (0x22, 0x5C):
            text.append(chr(value))
        else:
            text.append(f"\\x{value:02x}")
    return 'b"' + "".join(text) + '"'


def module_header(language, source_name, digest):
    return [
        MARKER,
        f"//! Snowball {language} stemmer, translated from PostgreSQL {PG_TAG}'s",
        f"//! `libstemmer/{source_name}` (Snowball commit {SNOWBALL_COMMIT}).",
        f"//! Source: {PG_TREE}/libstemmer/{source_name}",
        f"//! Source SHA-256: {digest}",
        "//! License: Snowball BSD 3-clause, reproduced in `mod.rs`.",
        "",
    ]


def stopword_module(source_dir):
    lines = [
        MARKER,
        f"//! Snowball stopword lists shipped by PostgreSQL {PG_TAG}.",
        f"//! Source: {PG_TREE}/stopwords",
        "//! Each list keeps every line up to its first whitespace, skips empty",
        "//! lines and is sorted bytewise for binary search, as `readstoplist` does.",
        "//! License: Snowball BSD 3-clause, reproduced in `mod.rs`.",
        "",
    ]
    names = []
    for path in sorted((source_dir / "stopwords").glob("*.stop")):
        raw = path.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        words = []
        for line in raw.decode("utf-8").split("\n"):
            word = re.split(r"[ \t\n\r\f\v]", line, maxsplit=1)[0]
            if word:
                if word != word.lower() and "İ" not in word:
                    raise TranslateError(f"{path.name} has an upper-case word {word!r}")
                words.append(word)
        words = sorted(set(words), key=lambda word: word.encode("utf-8"))
        const = path.stem.upper()
        names.append(path.stem)
        lines.append(f"/// `{path.name}`, SHA-256 {digest}.")
        lines.append(f"pub(super) const {const}: &[&str] = &[")
        for word in words:
            lines.append(f"    {rust_string(word)},")
        lines.append("];")
        lines.append("")
    return lines, names


def rust_string(word):
    return '"' + word.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()
    readme = (args.source / "README").read_text()
    if SNOWBALL_COMMIT not in readme:
        sys.exit(f"{args.source}/README is not synced with Snowball {SNOWBALL_COMMIT}")
    for language in LANGUAGES:
        name = f"stem_UTF_8_{language}.c"
        raw = (args.source / "libstemmer" / name).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        try:
            body = Translator(language, raw.decode("utf-8")).render()
        except TranslateError as error:
            sys.exit(f"{name}: {error}")
        imports = ["Among", "Env"] + [
            function for function in ("find_among", "find_among_b")
            if any(f"{function}(z," in line for line in body)
        ]
        header = module_header(language, name, digest) + [f"use super::{{{', '.join(imports)}}};", ""]
        text = "\n".join(header + body).rstrip() + "\n"
        (args.output / f"{language}.rs").write_text(text)
    lines, _ = stopword_module(args.source)
    (args.output / "stopwords.rs").write_text("\n".join(lines).rstrip() + "\n")


if __name__ == "__main__":
    main()
