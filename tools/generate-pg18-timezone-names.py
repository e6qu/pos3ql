#!/usr/bin/env python3
"""Generate the named time zones of PostgreSQL 18.6 from its tzdata.zi."""

import argparse
import hashlib
from pathlib import Path
import re


SOURCE = "https://raw.githubusercontent.com/postgres/postgres/REL_18_6/src/timezone/data/tzdata.zi"
SHA256 = "c63188e9f5017bb86bf93bcc12613cf4f814f6864119333fae06881b5b603814"


def generate(source):
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("zone names require the pinned PostgreSQL 18.6 tzdata.zi")
    names = set()
    for line in source.decode("ascii").splitlines():
        fields = line.split()
        if not fields or fields[0] not in ("Z", "L"):
            continue
        # A zone line names its zone; a link line names its alias last.
        name = fields[1] if fields[0] == "Z" else fields[2]
        if not re.fullmatch(r"[A-Za-z0-9/_+-]{1,48}", name) or name in names:
            raise ValueError(f"invalid or duplicate zone name: {name}")
        names.add(name)
    output = [
        "// Generated by tools/generate-pg18-timezone-names.py; do not edit.",
        f"// Source: {SOURCE}",
        f"// SHA256: {SHA256}",
        "// tzdata is in the public domain.",
        "",
        "/// The zones PostgreSQL 18.6 installs, sorted by byte value.",
        "#[rustfmt::skip]",
        "pub(crate) const NAMES: &[&str] = &[",
    ]
    output.extend(f'    "{name}",' for name in sorted(names))
    return "\n".join([*output, "];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.source.read_bytes()))
