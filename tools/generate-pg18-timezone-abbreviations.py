#!/usr/bin/env python3
"""Generate fixed/dynamic abbreviation definitions from PostgreSQL 18.6 Default."""

import argparse
import hashlib
from pathlib import Path
import re


SOURCE = "https://raw.githubusercontent.com/postgres/postgres/REL_18_6/src/timezone/tznames/Default"
SHA256 = "0dadd689b1998cc2d3acec42f66913194661f8d4835623776593b7bcdd075cb1"


def generate(source):
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("timezone definitions require the pinned PostgreSQL 18.6 Default file")
    definitions = {}
    for line in source.decode("ascii").splitlines():
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        name, value, *flags = fields
        if not name.isalpha() or not name.isupper() or len(name) > 8 or name in definitions:
            raise ValueError(f"invalid or duplicate abbreviation: {name}")
        if re.fullmatch(r"-?\d+", value):
            if flags not in ([], ["D"]):
                raise ValueError(f"invalid fixed abbreviation flags: {line}")
            definition = f"Fixed {{ offset: {int(value)}, is_dst: {str(bool(flags)).lower()} }}"
        else:
            if flags or not re.fullmatch(r"[A-Za-z/_-]+", value):
                raise ValueError(f"invalid dynamic abbreviation: {line}")
            definition = f'Dynamic("{value}")'
        definitions[name] = definition
    output = [
        "// Generated by tools/generate-pg18-timezone-abbreviations.py; do not edit.",
        f"// Source: {SOURCE}",
        f"// SHA256: {SHA256}",
        "// PostgreSQL License: vendor/test/postgres-regress/COPYRIGHT.",
        "use super::timezone::AbbreviationDefinition::{self, Dynamic, Fixed};",
        "",
        "#[rustfmt::skip]",
        "pub(crate) const DEFAULT: &[(&str, AbbreviationDefinition)] = &[",
    ]
    output.extend(f'    ("{name}", {definition}),' for name, definition in sorted(definitions.items()))
    return "\n".join([*output, "];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.source.read_bytes()))
