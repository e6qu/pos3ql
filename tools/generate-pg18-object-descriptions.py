#!/usr/bin/env python3
"""Write the pg_description text PostgreSQL 18.6 ships for built-in objects
other than routines.

usage: generate-pg18-object-descriptions.py --dsn DSN --mode write|check
       --output src/sql/catalog_object_descriptions.rs

Queries a PostgreSQL 18.6 reference server (database template1) for the
descriptions of schemas, languages, access methods, types and operators whose
OIDs initdb assigns from the catalog data files (below 10000, the same on every
platform), plus the plpgsql extension and language that initdb creates, keyed
by the OID the pinned CI image gives them. Built-in text search objects are keyed by name instead: initdb numbers
the snowball ones after importing the platform's collations. It writes both
lists sorted together with the SHA-256 digests of the extraction SQL and its
`psql -At` output. `check` fails when the
written file differs from what the server returns.
"""
import argparse, hashlib, json, subprocess, sys

parser = argparse.ArgumentParser()
parser.add_argument("--dsn", required=True, help="libpq connection string of a PostgreSQL 18.6 server")
parser.add_argument("--mode", choices=("write", "check"), required=True)
parser.add_argument("--output", required=True)
options = parser.parse_args()


def psql(sql):
    return subprocess.run(["psql", "-X", "-At", options.dsn, "-c", sql],
                          capture_output=True, text=True, check=True).stdout


version = psql("SHOW server_version").strip()
if not version.startswith("18.6"):
    sys.exit(f"reference server is {version}, not PostgreSQL 18.6")

classes = ("pg_namespace", "pg_language", "pg_am", "pg_type", "pg_operator")
text_search = (("pg_ts_parser", "prsname", "prsnamespace"),
               ("pg_ts_template", "tmplname", "tmplnamespace"),
               ("pg_ts_dict", "dictname", "dictnamespace"),
               ("pg_ts_config", "cfgname", "cfgnamespace"))
# initdb numbers plpgsql after the platform's collations; renumber it to the
# pinned CI image, where dsnowball_init (the first such object) is 13232.
pinned_oid = ("d.objoid::integer - CASE WHEN d.objoid >= 'dsnowball_init'::regproc "
              "THEN 'dsnowball_init'::regproc::integer - 13232 ELSE 0 END")
sql = ("SELECT coalesce(jsonb_agg(jsonb_build_array(d.classoid::integer, " + pinned_oid + ", "
       "d.description) ORDER BY d.classoid, d.objoid), '[]') FROM pg_description d "
       "WHERE d.objsubid = 0 AND (d.classoid::regclass::text IN ("
       + ", ".join(f"'{name}'" for name in classes)
       + ") AND d.objoid < 10000 OR d.classoid = 'pg_extension'::regclass AND d.objoid = "
       "(SELECT oid FROM pg_extension WHERE extname = 'plpgsql') OR d.classoid = "
       "'pg_language'::regclass AND d.objoid = (SELECT oid FROM pg_language "
       "WHERE lanname = 'plpgsql'))")
sql = ("SELECT jsonb_build_array((" + sql + "), (SELECT coalesce(jsonb_agg("
       "jsonb_build_array(classoid, name, description) ORDER BY classoid, name), '[]') FROM ("
       + " UNION ALL ".join(
           f"SELECT '{table}'::regclass::oid::integer AS classoid, o.{name}::text AS name, "
           f"d.description FROM {table} o JOIN pg_description d ON d.objoid = o.oid "
           f"AND d.classoid = '{table}'::regclass AND d.objsubid = 0 "
           f"WHERE o.{namespace} = 'pg_catalog'::regnamespace"
           for table, name, namespace in text_search)
       + ") t))")
output = psql(sql)
rows, text_search_rows = json.loads(output)

lines = [
    "//! `pg_description` text of built-in objects other than routines, queried",
    "//! from PostgreSQL 18.6. Generated by tools/generate-pg18-object-descriptions.py;",
    "//! do not edit.",
    "//! Extraction SQL SHA256: " + hashlib.sha256((sql + "\n").encode()).hexdigest(),
    "//! Result JSON SHA256: " + hashlib.sha256(output.encode()).hexdigest(),
    "//! https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_type.dat",
    "",
    "/// `(catalog OID, object OID, description)`, sorted by catalog then object.",
    "#[rustfmt::skip]",
    "pub(super) const OBJECT_DESCRIPTIONS: &[(i32, i32, &str)] = &[",
]
for classoid, objoid, description in rows:
    lines.append(f"    ({classoid}, {objoid}, {json.dumps(description, ensure_ascii=False)}),")
lines.append("];")
lines.append("")
lines.append("/// `(catalog OID, pg_catalog object name, description)` of built-in text search")
lines.append("/// objects, sorted by catalog then name.")
lines.append("#[rustfmt::skip]")
lines.append("pub(super) const TEXT_SEARCH_DESCRIPTIONS: &[(i32, &str, &str)] = &[")
for classoid, name, description in text_search_rows:
    lines.append(f"    ({classoid}, {json.dumps(name)}, {json.dumps(description, ensure_ascii=False)}),")
lines.append("];")
text = "\n".join(lines) + "\n"

if options.mode == "write":
    open(options.output, "w").write(text)
elif open(options.output).read() != text:
    sys.exit(f"{options.output} differs from the reference server")
