#!/usr/bin/env python3
"""Generate the declared domain of every information_schema view column.

Reads a running PostgreSQL 18.6 server through psql and writes a Rust table of
(view, column, domain) rows for columns declared with one of the
information_schema domains. Columns of built-in types are omitted.

Usage: tools/generate-pg18-information-schema-columns.py PSQL DSN OUTPUT
"""

import subprocess
import sys

DOMAINS = {
    "information_schema.cardinal_number": "CardinalNumber",
    "information_schema.character_data": "CharacterData",
    "information_schema.sql_identifier": "SqlIdentifier",
    "information_schema.time_stamp": "TimeStamp",
    "information_schema.yes_or_no": "YesOrNo",
}

QUERY = """
SELECT c.relname, a.attname, format_type(a.atttypid, NULL)
  FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
 WHERE c.relnamespace = 'information_schema'::regnamespace
   AND c.relkind IN ('v', 'r') AND a.attnum > 0 AND NOT a.attisdropped
 ORDER BY c.relname, a.attnum
"""


def psql(binary, dsn, sql):
    return subprocess.run(
        [binary, "-X", "-A", "-t", "-F", "\t", "-d", dsn, "-c", sql],
        check=True, capture_output=True, text=True,
    ).stdout


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    binary, dsn, output = sys.argv[1:]
    version = psql(binary, dsn, "SELECT version()").strip()
    if not version.startswith("PostgreSQL 18.6 "):
        sys.exit("information_schema columns require the pinned PostgreSQL 18.6 reference")
    rows = []
    for line in psql(binary, dsn, QUERY).splitlines():
        view, column, declared = line.split("\t")
        if declared in DOMAINS:
            rows.append((view, column, DOMAINS[declared]))
    if not rows:
        sys.exit("no information_schema domain columns found")
    lines = [
        "// Generated by tools/generate-pg18-information-schema-columns.py; do not edit.",
        f"// Source: {version}",
        "// PostgreSQL license: vendor/test/postgres-regress/COPYRIGHT",
        "use super::InformationSchemaDomain::{self, *};",
        "",
        "#[rustfmt::skip]",
        "pub(super) const COLUMNS: &[(&str, &str, InformationSchemaDomain)] = &[",
    ]
    lines += [f'    ("{view}", "{column}", {domain}),' for view, column, domain in rows]
    lines += ["];", ""]
    with open(output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


if __name__ == "__main__":
    main()
