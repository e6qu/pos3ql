#!/usr/bin/env python3
"""Write the pg_description text PostgreSQL 18.6 ships for built-in routines.

usage: generate-pg18-routine-descriptions.py --dsn DSN --mode write|check
       --signatures src/sql/catalog_callable_signatures.rs
       --output src/sql/catalog_routine_descriptions.rs

Reads the routine OIDs pos3ql lists in pg_proc from the callable-signature
table's CALLABLE_OIDS index, queries a PostgreSQL 18.6 reference server for
their `pg_description` rows, and writes them sorted by OID together with the
SHA-256 digests of the extraction SQL and its `psql -At` output. `check` fails
when the written file differs from what the server returns.
"""
import argparse, hashlib, json, re, subprocess, sys

parser = argparse.ArgumentParser()
parser.add_argument("--dsn", required=True, help="libpq connection string of a PostgreSQL 18.6 server")
parser.add_argument("--mode", choices=("write", "check"), required=True)
parser.add_argument("--signatures", required=True)
parser.add_argument("--output", required=True)
options = parser.parse_args()


def psql(sql):
    return subprocess.run(["psql", "-X", "-At", options.dsn, "-c", sql],
                          capture_output=True, text=True, check=True).stdout


version = psql("SHOW server_version").strip()
if not version.startswith("18.6"):
    sys.exit(f"reference server is {version}, not PostgreSQL 18.6")

signatures = open(options.signatures).read()
start = signatures.index("pub(super) const CALLABLE_OIDS")
index = signatures[start:signatures.index("];", start)]
oids = sorted({int(oid) for oid in re.findall(r"\((\d+), \d+\)", index)})
if not oids:
    sys.exit("no callable OIDs found")

# CALLABLE_OIDS number the routines initdb creates after the platform's
# collations as the pinned CI image does, where dsnowball_init is 13232.
pinned_oid = ("objoid::integer - CASE WHEN objoid >= 'dsnowball_init'::regproc "
              "THEN 'dsnowball_init'::regproc::integer - 13232 ELSE 0 END")
sql = ("SELECT coalesce(jsonb_agg(jsonb_build_array(" + pinned_oid + ", description) "
       "ORDER BY objoid), '[]') FROM pg_description "
       "WHERE classoid = 'pg_catalog.pg_proc'::regclass AND objsubid = 0 "
       "AND " + pinned_oid + " IN (" + ",".join(map(str, oids)) + ")")
output = psql(sql)
rows = json.loads(output)

lines = [
    "//! `pg_description` text of built-in routines, queried from PostgreSQL 18.6.",
    "//! Generated by tools/generate-pg18-routine-descriptions.py; do not edit.",
    "//! Routines: the CALLABLE_OIDS of catalog_callable_signatures.rs.",
    "//! Extraction SQL SHA256: " + hashlib.sha256((sql + "\n").encode()).hexdigest(),
    "//! Result JSON SHA256: " + hashlib.sha256(output.encode()).hexdigest(),
    "//! https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_proc.dat",
    "",
    "/// `(routine OID, description)`, sorted by OID.",
    "pub(super) const ROUTINE_DESCRIPTIONS: &[(i32, &str)] = &[",
]
for oid, description in rows:
    lines.append(f"    ({oid}, {json.dumps(description, ensure_ascii=False)}),")
lines.append("];")
text = "\n".join(lines) + "\n"

if options.mode == "write":
    open(options.output, "w").write(text)
elif open(options.output).read() != text:
    sys.exit(f"{options.output} differs from the reference server")
