#!/usr/bin/env python3
"""Translate PostgreSQL 18.6's default text search parser tables into Rust.

PostgreSQL's default parser (`src/backend/tsearch/wparser_def.c`) is a
table-driven state machine. This tool reads that exact file, plus the
non-spacing character table its `p_isspecial` test consults through
`pg_dsplen` (`src/include/common/unicode_nonspacing_table.h`), and writes the
token types, per-state action lists and character tables as Rust constants.
The runtime that interprets them is hand-ported in
`src/sql/text_parser/mod.rs`.

    python3 -I tools/generate-text-parser-tables.py \
        --source /path/to/postgres-REL_18_6 \
        --output src/sql/text_parser/tables.rs
"""

import argparse
import hashlib
import pathlib
import re
import sys

PG_TAG = "REL_18_6"
PG_BLOB = f"https://github.com/postgres/postgres/blob/{PG_TAG}"
MARKER = "//! @generated by tools/generate-text-parser-tables.py; do not edit."
PARSER = "src/backend/tsearch/wparser_def.c"
NONSPACING = "src/include/common/unicode_nonspacing_table.h"

# p_is* tests in wparser_def.c and the Rust `Class` variant each becomes.
CLASSES = {
    "p_isEOF": "Eof",
    "p_iseqC": "Eq",
    "p_isignore": "Ignore",
    "p_isasclet": "AsciiLetter",
    "p_isalpha": "Alpha",
    "p_isalnum": "Alnum",
    "p_isnotalnum": "NotAlnum",
    "p_isdigit": "Digit",
    "p_isxdigit": "HexDigit",
    "p_isspace": "Space",
    "p_isspecial": "Special",
    "p_isstophost": "StopHost",
    "p_ishost": "Host",
    "p_isURLPath": "UrlPath",
    "p_isurlchar": "UrlChar",
    "NULL": "Always",
}
SPECIALS = {
    "NULL": "None",
    "SpecialTags": "Tags",
    "SpecialFURL": "FullUrl",
    "SpecialHyphen": "Hyphen",
    "SpecialVerVersion": "VerVersion",
}
FLAGS = {
    "A_NEXT": 0x00, "A_BINGO": 0x01, "A_POP": 0x02, "A_PUSH": 0x04,
    "A_RERUN": 0x08, "A_CLEAR": 0x10, "A_MERGE": 0x20, "A_CLRALL": 0x40,
}
# Token types and states the runtime names directly.
NAMED_TOKENS = [
    "URL_T", "HOST", "SCIENTIFIC", "VERSIONNUMBER", "SPACE", "TAG_T", "PROTOCOL",
    "NUMHWORD", "ASCIIHWORD", "HWORD", "URLPATH", "DECIMAL_T", "SIGNEDINT",
    "UNSIGNEDINT", "XMLENTITY",
]
NAMED_STATES = ["TPS_Base", "TPS_InURLPathFirst"]


def fail(message):
    sys.exit(f"generate-text-parser-tables: {message}")


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def c_char(literal):
    if literal == "0":
        return 0
    match = re.fullmatch(r"'(\\?.)'", literal)
    if not match:
        fail(f"unexpected character literal {literal}")
    body = match.group(1)
    return ord(body[-1]) if body.startswith("\\") else ord(body)


def snake(name):
    return re.sub(r"(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).upper()


def string_array(source, name):
    match = re.search(rf"{name}\[\] = \{{(.*?)\}};", source, re.S)
    if not match:
        fail(f"missing {name}")
    return re.findall(r'"((?:[^"\\]|\\.)*)"', match.group(1))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True, type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    args = parser.parse_args()

    parser_bytes = (args.source / PARSER).read_bytes()
    nonspacing_bytes = (args.source / NONSPACING).read_bytes()
    source = strip_comments(parser_bytes.decode())

    token_defines = re.findall(r"#define\s+(\w+)\s+(\d+)\n", source)
    tokens = [(name, int(value)) for name, value in token_defines if name != "LASTNUM"]
    if [value for _, value in tokens] != list(range(1, 24)):
        fail("token type numbering changed")
    aliases = string_array(source, "tok_alias")
    descriptions = string_array(source, "lex_descr")
    if len(aliases) != 24 or len(descriptions) != 24:
        fail("token alias or description count changed")

    enum = re.search(r"typedef enum\s*\{(.*?)\}\s*TParserState;", source, re.S)
    states = [s.split("=")[0].strip() for s in enum.group(1).split(",") if s.strip()]
    if states[-1] != "TPS_Null":
        fail("TPS_Null is not the last state")
    states = states[:-1]
    order = re.findall(r"TPARSERSTATEACTION\((\w+)\)", source.split("Actions[] = {", 1)[1])
    if order != states:
        fail("Actions[] order does not match TParserState")

    item = re.compile(
        r"\{\s*(\w+)\s*,\s*('(?:\\.|[^'])'|0)\s*,\s*([A-Z_| ]+?)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\}"
    )
    actions = []
    starts = []
    for state in states:
        table = re.search(
            rf"actionTPS_{state[4:]}\[\]\s*=\s*\{{(.*?)\n\}};", source, re.S
        )
        if not table:
            fail(f"missing action table for {state}")
        starts.append(len(actions))
        for test, char, flags, to_state, token, special in item.findall(table.group(1)):
            if test not in CLASSES or special not in SPECIALS:
                fail(f"unknown test or handler in {state}: {test} {special}")
            if to_state != "TPS_Null" and to_state not in states:
                fail(f"unknown target state {to_state}")
            token_value = 0 if token == "0" else dict(tokens)[token]
            actions.append(
                (
                    CLASSES[test],
                    c_char(char),
                    sum(FLAGS[f.strip()] for f in flags.split("|")),
                    "NULL_STATE" if to_state == "TPS_Null" else str(states.index(to_state)),
                    token_value,
                    SPECIALS[special],
                    f"{state} {test} {char} {flags.strip()} {to_state} {token}",
                )
            )
        if actions[-1][0] != "Always":
            fail(f"{state} does not end with an unconditional action")
    starts.append(len(actions))

    strange = re.search(r"strange_letter\[\] = \{(.*?)\};", source, re.S)
    strange_letters = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", strange.group(1))]
    if strange_letters != sorted(strange_letters):
        fail("strange_letter is not sorted")
    nonspacing = [
        (int(a, 16), int(b, 16))
        for a, b in re.findall(r"\{0x([0-9A-F]+), 0x([0-9A-F]+)\}", nonspacing_bytes.decode())
    ]

    out = [
        MARKER,
        f"//! PostgreSQL {PG_TAG}'s default text search parser tables, from",
        f"//! [`{PARSER}`]({PG_BLOB}/{PARSER})",
        f"//! (SHA-256 {hashlib.sha256(parser_bytes).hexdigest()}) and",
        f"//! [`{NONSPACING}`]({PG_BLOB}/{NONSPACING})",
        f"//! (SHA-256 {hashlib.sha256(nonspacing_bytes).hexdigest()}).",
        "",
        "use super::{Action, Class, Handler};",
        "",
        "/// Token type numbers, as `wparser_def.c` defines them.",
    ]
    for name, value in tokens:
        if name in NAMED_TOKENS:
            out.append(f"pub(crate) const {name}: u8 = {value};")
    out += ["", "/// `tok_alias` and `lex_descr`, indexed by token type minus one."]
    out.append(f"pub(crate) const TOKEN_TYPES: [(&str, &str); {len(tokens)}] = [")
    for alias, description in zip(aliases[1:], descriptions[1:]):
        out.append(f'    ("{alias}", "{description}"),')
    out += ["];", ""]
    for name in NAMED_STATES:
        out.append(f"pub(super) const {snake(name[4:])}: u8 = {states.index(name)};")
    out.append("/// `TPS_Null`: an action that keeps the current state.")
    out.append(f"pub(super) const NULL_STATE: u8 = {len(states)};")
    out += ["", "/// Each state's first action in [`ACTIONS`], in `TParserState` order."]
    out.append(f"pub(super) const STATE_ACTIONS: [u16; {len(starts)}] = [")
    for state, start in zip(states + ["(end)"], starts):
        out.append(f"    {start}, // {state}")
    out += ["];", ""]
    out.append("/// Every state's action list, concatenated in `TParserState` order.")
    out.append(f"pub(super) const ACTIONS: [Action; {len(actions)}] = [")
    for cls, char, flags, to_state, token, special, comment in actions:
        out.append(f"    // {comment}")
        out.append(
            f"    Action {{ class: Class::{cls}, c: {char}, flags: 0x{flags:02x}, "
            f"to_state: {to_state}, token_type: {token}, handler: Handler::{special} }},"
        )
    out += ["];", ""]
    out.append("/// `p_isspecial`'s spacing combining marks, sorted for binary search.")
    out.append(f"pub(super) const STRANGE_LETTERS: [u32; {len(strange_letters)}] = [")
    for chunk in range(0, len(strange_letters), 8):
        out.append("    " + ", ".join(f"0x{v:04X}" for v in strange_letters[chunk:chunk + 8]) + ",")
    out += ["];", ""]
    out.append("/// Characters `pg_dsplen` reports as zero width (`nonspacing`).")
    out.append(f"pub(super) const NONSPACING: [(u32, u32); {len(nonspacing)}] = [")
    for low, high in nonspacing:
        out.append(f"    (0x{low:04X}, 0x{high:04X}),")
    out += ["];", ""]
    args.output.write_text("\n".join(out))


if __name__ == "__main__":
    main()
