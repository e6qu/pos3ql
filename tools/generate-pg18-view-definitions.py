#!/usr/bin/env python3
"""Generate built-in view SQL from retained PostgreSQL 18.6 metadata."""

import argparse
import hashlib
import json
from pathlib import Path


def generate(metadata_bytes, source):
    metadata = json.loads(metadata_bytes)
    version = metadata["version"]
    if not version.startswith("PostgreSQL 18.6 "):
        raise ValueError("view definitions require the pinned PostgreSQL 18.6 reference")
    definitions = sorted(
        (name, sql) for schema, name, sql in metadata["catalog_views"]
        if schema == "pg_catalog"
    )
    if not definitions or len({name for name, _ in definitions}) != len(definitions):
        raise ValueError("view definitions must be nonempty and uniquely named")
    if any(not isinstance(sql, str) or not sql.endswith(";") for _, sql in definitions):
        raise ValueError("view definitions must contain complete SQL")
    lines = [
        "// Generated by tools/generate-pg18-view-definitions.py; do not edit.",
        f"// Source: {version}",
        f"// Evidence: {source}",
        f"// Metadata SHA256: {hashlib.sha256(metadata_bytes).hexdigest()}",
        "// PostgreSQL license: vendor/test/postgres-regress/COPYRIGHT",
        "#[rustfmt::skip]",
        "pub(super) const DEFINITIONS: &[(&str, &str)] = &[",
    ]
    for name, sql in definitions:
        lines.append(f"    ({json.dumps(name)}, {json.dumps(sql, ensure_ascii=False)}),")
    lines.append("];\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", type=Path, required=True)
    parser.add_argument("--source", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--mode", choices=("write", "check"), required=True)
    arguments = parser.parse_args()
    generated = generate(arguments.metadata.read_bytes(), arguments.source)
    if arguments.mode == "write":
        arguments.output.write_text(generated)
    elif arguments.output.read_text().split("#[rustfmt::skip]\n", 1)[1] != generated.split("#[rustfmt::skip]\n", 1)[1]:
        raise SystemExit("built-in view definitions differ from PostgreSQL 18.6")


if __name__ == "__main__":
    main()
