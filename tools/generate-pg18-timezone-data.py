#!/usr/bin/env python3
"""Generate PostgreSQL 18.6's named time zones and their compiled TZif data.

PostgreSQL compiles its own tzdata.zi (release 2026c in 18.6) with zic and
installs the result in share/timezone. This generator compiles the same
pinned tzdata.zi with `zic -b slim` and embeds the files, so zone offsets are
PostgreSQL's and do not depend on the host's tzdata release. The compiled
bytes are pinned too: tzcode 2022g's `zic -b slim` reproduces PostgreSQL
18.6's installed files byte for byte, and any other output is rejected.
"""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import tempfile


SOURCE = "https://raw.githubusercontent.com/postgres/postgres/REL_18_6/src/timezone/data/tzdata.zi"
SHA256 = "c63188e9f5017bb86bf93bcc12613cf4f814f6864119333fae06881b5b603814"
# SHA-256 over every zone's name, a NUL byte, its TZif bytes and a NUL byte,
# in byte order of the names.
DATA_SHA256 = "7183496f58bf6dde046a59ce9f53a99dd6b7db6cd26b9a8923691fd31907c35f"


def zone_names(source):
    names = set()
    for line in source.decode("ascii").splitlines():
        fields = line.split()
        if not fields or fields[0] not in ("Z", "L"):
            continue
        # A zone line names its zone; a link line names its alias last.
        name = fields[1] if fields[0] == "Z" else fields[2]
        if not re.fullmatch(r"[A-Za-z0-9/_+-]{1,48}", name) or name in names:
            raise ValueError(f"invalid or duplicate zone name: {name}")
        names.add(name)
    return sorted(names)


def compile_zones(source_path, zic, names):
    with tempfile.TemporaryDirectory() as output:
        subprocess.run([zic, "-b", "slim", "-d", output, str(source_path)], check=True)
        root = Path(output)
        files = {}
        for name in names:
            data = (root / name).read_bytes()
            if not data.startswith(b"TZif"):
                raise ValueError(f"zic wrote no TZif file for {name}")
            files[name] = data
        return files


def digest(names, files):
    hasher = hashlib.sha256()
    for name in names:
        hasher.update(name.encode("ascii") + b"\0" + files[name] + b"\0")
    return hasher.hexdigest()


def byte_literal(data):
    out = []
    for byte in data:
        if 0x20 <= byte < 0x7F and byte not in (0x22, 0x5C):
            out.append(chr(byte))
        else:
            out.append(f"\\x{byte:02x}")
    return 'b"' + "".join(out) + '"'


def generate(source_path, zic):
    source = source_path.read_bytes()
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("zone data requires the pinned PostgreSQL 18.6 tzdata.zi")
    names = zone_names(source)
    files = compile_zones(source_path, zic, names)
    data_sha256 = digest(names, files)
    if data_sha256 != DATA_SHA256:
        raise ValueError(f"zic output {data_sha256} is not PostgreSQL 18.6's zone data")
    blobs = []
    index = {}
    zone_blobs = []
    for name in names:
        data = files[name]
        if data not in index:
            index[data] = len(blobs)
            blobs.append(data)
        zone_blobs.append(index[data])
    output = [
        "// Generated by tools/generate-pg18-timezone-data.py; do not edit.",
        f"// Source: {SOURCE}",
        f"// SHA256: {SHA256}",
        "// Compiled with `zic -b slim`, byte-identical to the TZif files",
        "// PostgreSQL 18.6 installs in share/timezone.",
        "// tzdata is in the public domain.",
        "",
        "/// The zones PostgreSQL 18.6 installs, sorted by byte value.",
        "#[rustfmt::skip]",
        "pub(crate) const NAMES: &[&str] = &[",
    ]
    output.extend(f'    "{name}",' for name in names)
    output += [
        "];",
        "",
        "/// Each zone's TZif file in [`FILES`], in [`NAMES`] order.",
        "#[rustfmt::skip]",
        "pub(crate) const ZONE_FILES: &[u16] = &[",
    ]
    output.extend(f"    {blob}," for blob in zone_blobs)
    output += [
        "];",
        "",
        "/// The distinct TZif files; zones linked to one another share one.",
        "#[rustfmt::skip]",
        "pub(crate) const FILES: &[&[u8]] = &[",
    ]
    output.extend(f"    {byte_literal(blob)}," for blob in blobs)
    output += [
        "];",
        "",
        "/// SHA-256 over every zone's name, a NUL byte, its TZif bytes and a NUL",
        "/// byte, in [`NAMES`] order.",
        f'pub(crate) const SHA256: &str = "{data_sha256}";',
        "",
    ]
    return "\n".join(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="REL_18_6 src/timezone/data/tzdata.zi")
    parser.add_argument("zic", help="the zic executable (tzcode 2022g reproduces the pin)")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.source, args.zic))
