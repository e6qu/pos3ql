#!/usr/bin/env python3
"""Generate internal type-I/O planner facts from pinned PostgreSQL sources."""

import argparse
import hashlib
from pathlib import Path
import re


def catalog_rows(source):
    rows = []
    start = None
    quoted = escaped = comment = False
    for at, character in enumerate(source):
        if comment:
            if character == "\n":
                comment = False
        elif quoted:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == "'":
                quoted = False
        elif character == "#":
            comment = True
        elif character == "'":
            quoted = True
        elif character == "{":
            assert start is None
            start = at + 1
        elif character == "}" and start is not None:
            fields = dict(re.findall(r"(\w+)\s*=>\s*'((?:\\.|[^'])*)'", source[start:at]))
            assert "oid" in fields
            rows.append(fields)
            start = None
    assert start is None and not quoted
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--type-io-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()
    source = arguments.source.read_bytes()
    header = arguments.header.read_bytes()
    type_io_source = arguments.type_io_source.read_bytes()
    source_sha = hashlib.sha256(source).hexdigest()
    header_sha = hashlib.sha256(header).hexdigest()
    type_io_sha = hashlib.sha256(type_io_source).hexdigest()
    assert source_sha == "1f934ce80d460159dda137714374a35f9896315ea2476709cbb4da13b38ef95a"
    assert header_sha == "f7d59f07c5b95e2f3c7141762a0f576e8a3af7581ba54c27537f4d500472bea5"
    assert type_io_sha == "4d5522b2d62607be97ba02bbffe5144c5957bb0022a55d23e485c00f29f9b108"
    defaults = dict(re.findall(r"\b(pro\w+)\s+BKI_DEFAULT\(([^)]+)\)", header.decode()))
    rows = sorted(catalog_rows(source.decode()), key=lambda row: int(row["oid"]))
    assert len(rows) == len({row["oid"] for row in rows}) == 3397
    type_io = type_io_source.decode().split("const TYPE_IO:", 1)[1].split("];", 1)[0]
    selected = {
        int(procedure)
        for _, input_oid, output_oid in re.findall(r"\((\d+), (\d+), (\d+)\)", type_io)
        for procedure in (input_oid, output_oid)
    }
    assert len(selected) == 194
    rows = [row for row in rows if int(row["oid"]) in selected]
    assert len(rows) == len(selected)
    lines = [
        "//! Internal type-I/O facts supplement verified callable declarations.",
        "//! Generated by tools/generate-pg18-planner-properties.py.",
        "//! Sources: https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_proc.dat",
        "//! https://github.com/postgres/postgres/blob/REL_18_6/src/include/catalog/pg_proc.h",
        f"//! pg_proc.dat SHA256: {source_sha}",
        f"//! pg_proc.h SHA256: {header_sha}",
        f"//! catalog_builtin_properties.rs SHA256: {type_io_sha}",
        "",
        "use super::BuiltinPlannerProcedure;",
        "",
        "#[rustfmt::skip]",
        "pub(super) const PROCEDURES: &[(i32, BuiltinPlannerProcedure)] = &[",
    ]
    for row in rows:
        facts = defaults | row
        assert facts["prolang"] == "internal"
        volatility = {"i": 0, "s": 1, "v": 2}[facts["provolatile"]]
        strict = {"t": "true", "f": "false"}[facts["proisstrict"]]
        forbidden = facts["prokind"] != "f" or facts["proretset"] != "f"
        cost = float(facts["procost"])
        assert cost > 0
        lines.append(
            f'    ({row["oid"]}, BuiltinPlannerProcedure {{ volatility: {volatility}, '
            f'strict: {strict}, cost: {cost!r}, forbidden: {str(forbidden).lower()} }}),'
        )
    lines.append("];")
    arguments.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
